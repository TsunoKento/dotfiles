#!/usr/bin/env bash
set -euo pipefail

# =============================================================================
# メイン
# =============================================================================
zshrc="${HOME}/.zshrc"

# シンボリックリンクがあれば削除
if [[ -L "$zshrc" ]];then
	rm -f "$zshrc"
	echo "Deleted symlink: $zshrc"
fi
