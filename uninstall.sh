#!/usr/bin/env zsh
set -euo pipefail

# =============================================================================
# 設定
# =============================================================================
DOTFILES_DIR="$(cd "$(dirname "$0")" && pwd)"

# =============================================================================
# メイン
# =============================================================================
while IFS=: read -r src dst; do
	# コメント行と空行をスキップ
	[[ "$src" =~ ^# ]] && continue
	[[ -z "$src" ]] && continue

	# 変数を展開
	dst=$(eval echo "$dst")

	if [[ -L "$dst" ]]; then
		rm -f "$dst"
		echo "Deleted symlink: $dst"
	fi
done < "${DOTFILES_DIR}/symlinks.conf"
